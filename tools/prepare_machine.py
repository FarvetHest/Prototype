"""Extract RAM/SST constants and original object-state tables from pinned BK3."""
import hashlib, json, re
from pathlib import Path
from import_bk3 import ROOT, SHA
raw=(ROOT/'original/vendor/BK3.asm').read_bytes()
assert hashlib.sha256(raw).hexdigest()==SHA
s=raw.decode('latin-1'); lines=s.splitlines()
equ={}
for line in lines[:210]:
 m=re.match(r'^(\w+):\s*equ\s+(\$[\dA-Fa-f]+|\d+)\b',line)
 if m:equ[m[1]]=int(m[2][1:],16) if m[2].startswith('$') else int(m[2])
tables={}
for name,anchor in [('garcia','loc_262F8'),('electra','loc_2AF3A'),('zack','loc_2B8DA'),('blondie','loc_2B878')]:
 start=next(i for i,l in enumerate(lines) if l.startswith(anchor+':'))
 entries={}; begun=False
 for n in range(start+1,len(lines)):
  code=lines[n].split(';')[0].strip()
  m=re.fullmatch(r'dc\.l\s+(\w+)',code)
  if m:entries[2*(len(entries)+1)]=dict(label=m[1],line=n+1);begun=True
  elif begun and code:break
 tables[name]=entries
tables['axel']={}
for n,line in enumerate(lines):
 m=re.match(r'Obj_Axel_([\dA-F]{2}):\s*dc\.w\s+(.+?)(?:\s*;|$)',line)
 if m:
  expr=m[2].strip();label=expr.split('-Obj_Axel_')[0]
  tables['axel'][int(m[1],16)]=dict(label=label,line=n+1,expression=expr,unresolved=not bool(re.fullmatch(r'[A-Za-z_]\w*',label)))
assert tables['zack'][0x1a]['label']=='sub_2C80E'
assert tables['electra'][4]['label']=='Enemy_Hit'
header=['/* Generated by tools/prepare_machine.py from pinned BK3; do not edit. */','#ifndef BK3_MACHINE_DATA_H','#define BK3_MACHINE_DATA_H','enum {']
header += [' BK3_'+k+'=0x'+format(v,'x')+'u,' for k,v in equ.items()]
header += ['};','typedef struct { unsigned short mode; const char *label; } Bk3StateEntry;']
for name,entries in tables.items():
 header+=['static const Bk3StateEntry bk3_states_'+name+'[]={']
 header += [' {0x%x,"%s"},'%(mode,e['label']) for mode,e in entries.items() if not e.get('unresolved')]
 header+=['};']
header+=['#endif','']
(ROOT/'src/machine_data.h').write_text('\n'.join(header))
audit=dict(source_sha256=SHA,constants=equ,tables=tables,
 loader=dict(label='LoadEnemyObj',start='BossObjSST',slots=6,stride=256,skip='ObjMode == 0',timer='word at SST+0x5c: decrement once if nonzero',post=['sub_23102','sub_22C8C','sub_23EBA']),
 warning='Literal IDA table expressions preserved; unresolved Axel word offsets are not guessed.')
(ROOT/'assets/machine-source.json').write_text(json.dumps(audit,indent=2)+'\n')
print(json.dumps({n:len(t) for n,t in tables.items()}))
